#!/bin/bash

# --- НАСТРОЙКИ ---
KEY_NAME="ed25519_key" # Базовое имя для файлов ключей
# ------------------

PRIV_KEY="${KEY_NAME}.pem"
PUB_KEY="${KEY_NAME}_pub.pem"

# 1. Генерация ключевой пары Ed25519 и сохранение закрытого ключа в PEM
echo "Генерация закрытого ключа Ed25519..."
openssl genpkey -algorithm ed25519 -out "$PRIV_KEY"

# Проверка успешности генерации
if [ $? -ne 0 ]; then
    echo "Ошибка: Не удалось сгенерировать закрытый ключ."
    exit 1
fi

# 2. Извлечение открытого ключа в формате X.509 (SPKI)
echo "Извлечение открытого ключа в формате X.509..."
openssl pkey -in "$PRIV_KEY" -pubout -out "$PUB_KEY"

# Проверка успешности извлечения
if [ $? -ne 0 ]; then
    echo "Ошибка: Не удалось извлечь открытый ключ."
    rm "$PRIV_KEY" # Удаляем закрытый ключ, если открытый не создался
    exit 1
fi

echo "Готово!"
echo "Закрытый ключ (PEM): $PRIV_KEY"
echo "Открытый ключ (X.509/PEM): $PUB_KEY"